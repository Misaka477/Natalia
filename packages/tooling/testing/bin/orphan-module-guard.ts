/**
 * Orphan-module guard.
 *
 * A module with tests but no product caller is a hallucination with a green
 * checkmark: its unit tests pass, the coverage looks fine, and nothing in the
 * shipped application ever runs it. This session produced five of them —
 * `instance.ts` was the clearest, a complete single-instance protocol that
 * nothing created the socket for — and each was found by accident in a later
 * round rather than by anything mechanical.
 *
 * This mechanizes that screen so the next one is CI's fault, not a reader's.
 *
 * The guard is deliberately narrow, because a naive "unimported file" check has
 * too many true positives to be useful:
 *
 *   - only `src/` production modules are considered, never tests or manifests;
 *   - an entry point (`main.ts`, `index.ts`, a plugin's `index`) is excluded,
 *     because the runtime loads those by path, not by import;
 *   - a module referenced from a NON-module artifact is fine: a shell script, a
 *     CMake list, or a package.json script may be its caller (AppRun carries the
 *     spec that `instance.ts` implements in TS);
 *   - anything else is an orphan, and it must be named in ALLOWED with a reason
 *     or connected to the product. A stale entry fails the gate, matching the
 *     contract-producer guard's discipline.
 */
import { existsSync } from "node:fs";
import { readdir, readFile } from "node:fs/promises";
import { join, relative } from "node:path";

// Injectable so the guard's own test can drive it against a synthetic tree;
// the default is the working directory a CI run invokes it from.
const root = process.env.ORPHAN_GUARD_ROOT ?? process.cwd();
const sourceRoots = ["packages", "apps"];
const skipDirs = new Set([
  "node_modules",
  "dist",
  ".turbo",
  "coverage",
  "build",
  "out",
  "target",
  "wezterm",
]);

/** Files the runtime reaches by path rather than by import. */
const ENTRY_BASENAMES = new Set([
  "index.ts",
  "index.tsx",
  "main.ts",
  "serve-web.ts",
  // The web shell's two builds (the app proper and the light/embedded one); the
  // bundler reaches them by path.
  "main-neu.ts",
  "main-neu-light.ts",
]);

/**
 * Known orphans, each with why it is legitimate.
 *
 * The reason must name the caller. "It is tested" is not a reason — that is the
 * failure mode this gate exists for.
 */
const ALLOWED: Readonly<Record<string, string>> = {
  // AppRun (generated by scripts/appimage.ts) implements this protocol in shell,
  // because it runs before any runtime exists. The TS module is the protocol's
  // unit-level twin, and window-policy's cross-check pins the two together.
  "apps/cef-desktop/src/instance.ts":
    "called by AppRun, the shell launcher scripts/appimage.ts generates",
  // The C++ `MinimiseOnClose()` in simple_app.cc is the product; this module is
  // the test-reachable mirror, and window-policy.test.ts asserts the two agree.
  "apps/cef-desktop/src/window-policy.ts":
    "mirrors simple_app.cc's MinimiseOnClose; cross-checked by window-policy.test.ts",
  // The D6b external-benchmark adapter. MEASURED, not assumed: calling
  // `eval.external_benchmark` against a runtime without the member returns
  // `notSupported` from the transport's optionsGuard BEFORE the route's
  // `{joined:false, reason:"no_eval_dir"}` fallback can answer — so that
  // fallback is unreachable and the caller cannot even be told to name a
  // directory. (I recorded the opposite here first, having read the contract's
  // comment instead of running it.) The adapter itself is a pure library for
  // whoever runs the benchmark; whether runtime should expose it at all is an
  // open question this entry keeps visible.
  "packages/tooling/testing/src/eval-adapter.ts":
    "called by the external benchmark harness, which lives outside this repo; the rpc route's `joined:false` fallback is the contract's designed answer, not a gap",
};

async function* sourceFiles(dir: string): AsyncGenerator<string> {
  let entries;
  try {
    entries = await readdir(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (skipDirs.has(entry.name)) continue;
      yield* sourceFiles(join(dir, entry.name));
    } else if (/\.(ts|tsx)$/.test(entry.name) && !/\.d\.ts$/.test(entry.name)) {
      yield join(dir, entry.name);
    }
  }
}

const isProductionSource = (file: string) => {
  const normalised = file.replaceAll("\\", "/");
  return (
    /\/src\//.test(normalised) &&
    !/\.(test|spec)\.(ts|tsx)$/.test(normalised) &&
    !/\/test\//.test(normalised)
  );
};

/**
 * Every text artifact that could reference a module by path.
 *
 * TEST files are excluded, and that is not tidiness: a test that names a module
 * proves nothing about the product calling it — it is exactly what a
 * "tested but never used" module looks like. This guard's own test names
 * `unreferenced.ts` on purpose, and counting it as a reference was how the first
 * version of the test quietly passed.
 */
async function referencingArtifacts(): Promise<string[]> {
  const texts: string[] = [];
  const roots = [
    ...sourceRoots,
    "scripts",
    "docs",
    "composition.base.json",
    "package.json",
  ];
  for (const base of roots) {
    // A FILE root (package.json, composition.base.json) is read directly; a
    // DIRECTORY root is walked. Reading only directories is how the first version
    // missed `scripts/composition-dts.ts`, which imports a module under
    // packages/core/composition/src.
    let entries;
    try {
      const stat = await Bun.file(join(root, base)).stat();
      if (!stat.isDirectory()) {
        texts.push(await readFile(join(root, base), "utf8"));
        continue;
      }
      entries = await readdir(join(root, base), { withFileTypes: true });
    } catch {
      continue;
    }
    for (const entry of entries) {
      if (
        entry.isFile() &&
        /\.(json|ya?ml|sh|cmd|ps1|txt|cc|h|cmake|ts|tsx)$/i.test(entry.name)
      ) {
        const top = join(root, base, entry.name);
        const topNorm = top.replaceAll("\\", "/");
        if (topNorm.includes("/test/")) continue;
        texts.push(await readFile(top, "utf8"));
        continue;
      }
      if (entry.isDirectory()) {
        if (skipDirs.has(entry.name)) continue;
        for await (const file of sourceFiles(join(root, base, entry.name))) {
          const normalised = file.replaceAll("\\", "/");
          if (
            /\.(test|spec)\.(ts|tsx)$/.test(normalised) ||
            /\/test\//.test(normalised)
          )
            continue;
          texts.push(await readFile(file, "utf8"));
        }
      } else if (/\.(json|ya?ml|sh|cmd|ps1|txt|cc|h|cmake)$/i.test(entry.name))
        texts.push(await readFile(join(root, base, entry.name), "utf8"));
    }
  }
  return texts;
}

const failures: string[] = [];
const allowedStillPresent = new Set<string>();
let scanned = 0;

const artifacts = await referencingArtifacts();
// One pass: a module is referenced if ANY artifact mentions it. Import
// specifiers omit the extension (`from "./constitution"`), so the basename is
// matched WITHOUT its suffix as well as with one — matching only `.ts`-suffixed
// spellings reported 412 false positives on the first run, because essentially
// every import in this repository is extension-less.
const mentioned = new Set<string>();
for (const text of artifacts)
  for (const match of text.matchAll(/[\w.-]+\.?(?:ts|tsx)?\b/gu)) {
    if (!match[0]) continue;
    mentioned.add(match[0]);
    mentioned.add(match[0].replace(/\.(?:ts|tsx)$/u, ""));
  }

for (const base of sourceRoots) {
  for await (const file of sourceFiles(join(root, base))) {
    if (!isProductionSource(file)) continue;
    const rel = relative(root, file).replaceAll("\\", "/");
    if (ENTRY_BASENAMES.has(file.split(/[\\/]/).pop()!)) continue;
    scanned += 1;
    const basename = file.split(/[\\/]/).pop()!;
    const stem = basename.replace(/\.(?:ts|tsx)$/u, "");
    if (mentioned.has(stem) || mentioned.has(basename)) continue;
    const reason = ALLOWED[rel];
    if (reason !== undefined) {
      allowedStillPresent.add(rel); // the orphan is real, and its reason stands
      continue;
    }
    failures.push(
      `${rel}: no product caller and no ALLOWED entry — connect it, or record why it is legitimate (its caller must be named)`,
    );
  }
}

// A stale entry is a module that is no longer on disk, or that HAS gained a
// caller (and is therefore never visited by the orphan branch above).
for (const [rel, reason] of Object.entries(ALLOWED))
  if (!allowedStillPresent.has(rel) && !existsSync(join(root, rel)))
    failures.push(`${rel}: ALLOWED entry is stale (${reason}) — remove it`);

if (failures.length) {
  console.error(`orphan-module guard: ${failures.length} finding(s)`);
  for (const failure of failures) console.error(`  ${failure}`);
  process.exit(1);
}
console.log(`orphan-module guard: ${scanned} modules, every one has a caller`);
